"""
WORK IN PROGRESS: with WarpX 26.10 (conda-forge, no PETSc) the implicit
Newton solve does not converge on the first step with the point-Jacobi
preconditioner (the curl-curl MLMG preconditioner does not accept the
`none` axis boundary of RCYLINDER). Not yet used for any result.

Generate WarpX (1D cylindrical, fully kinetic PIC) input decks for the HOFI
channel density scan, with the same initial state and the same collision
cross-sections as the hybrid (UGKWP / particle-BGK / fluid) runs.

usage: python3 make_inputs.py n0 [out_dir]

Physics in WarpX:
  * electrons, H+ and H as macro-particles; energy-conserving theta-implicit
    electromagnetic PIC (Angus et al.) so that cells need not resolve the
    Debye length and dt need not resolve 1/omega_pe;
  * binary Coulomb collisions e-e, e-i, i-i (Perez et al., WarpX defaults);
  * DSMC: H+ + H charge exchange (5e-19 m^2), H-H elastic (VHS, omega = 0.7),
    e-H elastic (CHEQUP/LXCat fit) and e-H ionization (CHEQUP BEB cross
    section, 13.6 eV).
Not available in WarpX and therefore switched off in the matched hybrid
runs: 3-body recombination, the excitation-mediated ionization channel.
"""
import os
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from benchmark_1e24 import NE_NODES, TE_NODES_EV, parser_expr, T_HEAVY   # noqa: E402
import chequp_rates as cr                                                   # noqa: E402

KB = 1.380649e-23
QE = 1.602176634e-19
ME = 9.1093837015e-31
MH = 1.6735575e-27
C = 299792458.0

# shared model parameters (identical in hofi.HOFIChannel)
SIGMA_CX = 5e-19
D_HH = 2.5e-10
OMEGA_HH = 0.7
R_MAX = 120e-6
NCELL = 240
T_SNAP = [0.5e-9, 1.0e-9, 2.0e-9]


def write_cross_sections(d):
    E = np.logspace(-4, 4, 400)
    np.savetxt(f'{d}/cx_H.dat', np.c_[E, np.full_like(E, SIGMA_CX)])
    # VHS: sigma_T = pi d^2 (E / kT_ref)^-(omega-1/2), E = centre-of-mass energy
    Eref = KB * T_HEAVY / QE
    np.savetxt(f'{d}/el_HH.dat', np.c_[E, np.pi * D_HH ** 2 * (E / Eref) ** (-(OMEGA_HH - 0.5))])
    Ee = np.logspace(-3, 3, 400)
    np.savetxt(f'{d}/el_eH.dat', np.c_[Ee, cr.sigma_en_H(np.log(np.clip(Ee, 0.05, 300)))])
    Ei = np.concatenate([[13.598434], np.logspace(np.log10(13.6), 3, 400)[1:]])
    np.savetxt(f'{d}/ion_eH.dat', np.c_[Ei, [cr._sigma_direct_cm2(e) * 1e-4 for e in Ei]])


def deck(n0, dt=2.0e-13, ppc=100, nthreads=4):
    ne_expr = parser_expr([n0 * v for v in NE_NODES])
    nn_expr = parser_expr([n0 * (1 - v) for v in NE_NODES])
    theta_e = parser_expr([t * QE / (ME * C ** 2) for t in TE_NODES_EV])
    theta_h = KB * T_HEAVY / (MH * C ** 2)
    steps = [int(round(t / dt)) for t in T_SNAP]
    return f"""# generated by make_inputs.py: HOFI channel, n0 = {n0:.3e} m^-3
max_step = {steps[-1]}
amr.n_cell = {NCELL}
amr.max_level = 0
amr.max_grid_size = {NCELL}
geometry.dims = RCYLINDER
geometry.prob_lo = 0.0
geometry.prob_hi = {R_MAX}

boundary.field_lo = none
boundary.field_hi = pec
boundary.particle_lo = none
boundary.particle_hi = reflecting

warpx.const_dt = {dt}
warpx.use_filter = 0
warpx.verbose = 1
warpx.serialize_initial_conditions = 1
warpx.random_seed = 1

algo.maxwell_solver = Yee
algo.evolve_scheme = theta_implicit_em
implicit_evolve.theta = 0.5
implicit_evolve.max_particle_iterations = 21
implicit_evolve.particle_tolerance = 1.0e-10
implicit_evolve.particle_suborbits = true
implicit_evolve.nonlinear_solver = newton
implicit_evolve.use_mass_matrices_jacobian = true
implicit_evolve.use_mass_matrices_pc = true
jacobian.pc_type = pc_jacobi
pc_jacobi.verbose = false
newton.verbose = false
newton.max_iterations = 30
newton.relative_tolerance = 1.0e-6
newton.require_convergence = false
newton.diagnostic_file = diags/newton.txt
newton.diagnostic_interval = 50
gmres.verbose_int = 0
gmres.max_iterations = 200
gmres.relative_tolerance = 1.0e-5
particles.max_grid_crossings = 2
algo.particle_shape = 1
algo.current_deposition = villasenor
algo.particle_pusher = boris

particles.species_names = electrons Hplus H

electrons.charge = -q_e
electrons.mass = m_e
electrons.injection_style = NUniformPerCell
electrons.num_particles_per_cell_each_dim = {ppc} 1
electrons.radial_numpercell_power = 0
electrons.random_theta = true
electrons.profile = parse_density_function
electrons.density_function(x,y,z) = "{ne_expr}"
electrons.density_min = {1e-6 * n0}
electrons.momentum_distribution_type = maxwell_juttner
electrons.theta_distribution_type = parser
electrons.theta_function(x,y,z) = "{theta_e}"

Hplus.charge = q_e
Hplus.mass = {MH - ME}
Hplus.injection_style = NUniformPerCell
Hplus.num_particles_per_cell_each_dim = {ppc} 1
Hplus.radial_numpercell_power = 0
Hplus.random_theta = true
Hplus.profile = parse_density_function
Hplus.density_function(x,y,z) = "{ne_expr}"
Hplus.density_min = {1e-6 * n0}
Hplus.momentum_distribution_type = maxwell_juttner
Hplus.theta = {theta_h}

H.charge = 0
H.mass = {MH}
H.injection_style = NUniformPerCell
H.num_particles_per_cell_each_dim = {ppc} 1
H.radial_numpercell_power = 0
H.random_theta = true
H.profile = parse_density_function
H.density_function(x,y,z) = "{nn_expr}"
H.density_min = {1e-6 * n0}
H.momentum_distribution_type = maxwell_juttner
H.theta = {theta_h}

collisions.collision_names = cee cei cii cx hh eh
cee.species = electrons electrons
cei.species = electrons Hplus
cii.species = Hplus Hplus
cx.type = dsmc
cx.species = Hplus H
cx.product_species = H Hplus
cx.scattering_processes = charge_exchange
cx.charge_exchange_cross_section = cx_H.dat
hh.type = dsmc
hh.species = H H
hh.scattering_processes = elastic
hh.elastic_cross_section = el_HH.dat
eh.type = dsmc
eh.species = electrons H
eh.product_species = electrons Hplus
eh.scattering_processes = elastic ionization
eh.elastic_cross_section = el_eH.dat
eh.ionization_cross_section = ion_eH.dat
eh.ionization_energy = 13.598434
eh.ionization_target_species = H

diagnostics.diags_names = diag1
diag1.diag_type = Full
diag1.format = openpmd
diag1.openpmd_backend = h5
diag1.intervals = 0,{steps[0]},{steps[1]},{steps[2]}
diag1.fields_to_plot = Er rho
diag1.species = electrons Hplus H
diag1.electrons.variables = x y w ux uy uz
diag1.Hplus.variables = x y w ux uy uz
diag1.H.variables = x y w ux uy uz

warpx.reduced_diags_names = pe fe
pe.type = ParticleEnergy
pe.intervals = 100
fe.type = FieldEnergy
fe.intervals = 100
"""


if __name__ == '__main__':
    n0 = float(sys.argv[1])
    out = sys.argv[2] if len(sys.argv) > 2 else f'run_n{n0:.0e}'
    os.makedirs(out, exist_ok=True)
    write_cross_sections(out)
    extra = {}
    if len(sys.argv) > 3:
        extra['dt'] = float(sys.argv[3])
    open(f'{out}/inputs', 'w').write(deck(n0, **extra))
    print(out)
